/**
 * completion_scripts.ts — the bash, zsh and fish completion scripts, generated from the live
 * command list.
 *
 * In here: `completionTable` (every command path with its options and summary, plus the app
 * commands read from the usage lines `bin/telenow.mjs` passes in — so neither list is kept twice)
 * and `bashScript`, `zshScript`, `fishScript`. What they complete: the first word (command
 * groups, single commands, app commands), the second word inside a group, and then the options of
 * the command typed so far plus the global options; anything else completes file names (most
 * values are files or ids).
 * zsh uses the bash function through zsh's own `bashcompinit`, so the two never disagree.
 * Not in here: printing them (`completion.ts`).
 * Called by: `completion.ts`; tests.
 */

import type { CommandSpec, OptionSpec } from '../../core/command_spec.js';
import { GLOBAL_OPTIONS } from '../../core/global_options.js';

export interface CompletionEntry {
  path: string[];
  summary: string;
  options: string[];
}

export interface CompletionTable {
  entries: CompletionEntry[];
  globals: string[];
  /** First words of the app commands (`app`, `dev`, `validate`, `build`, …). */
  appWords: { word: string; second?: string; summary: string }[];
}

const longNames = (o: Record<string, OptionSpec> | undefined) => Object.keys(o ?? {}).map((n) => `--${n}`);

/** "  telenow app init <name>   scaffold a new app" → { word: 'app', second: 'init', summary }. */
function appWords(appUsage: string | undefined): CompletionTable['appWords'] {
  const out: CompletionTable['appWords'] = [];
  for (const line of (appUsage ?? '').split('\n')) {
    const m = /^\s*telenow\s+(.*?)\s{2,}(.*)$/.exec(line);
    if (!m) continue;
    const words = m[1].split(/\s+/).filter((w) => !/^[<[-]/.test(w));
    if (words.length === 0) continue;
    out.push({ word: words[0], second: words[1], summary: m[2].trim() });
  }
  return out;
}

export function completionTable(commands: CommandSpec[], appUsage: string | undefined): CompletionTable {
  return {
    entries: commands.map((c) => ({ path: c.path, summary: c.summary, options: longNames(c.options) })),
    globals: [...longNames(GLOBAL_OPTIONS), '-h'],
    appWords: appWords(appUsage),
  };
}

function firstWords(t: CompletionTable): string[] {
  const words = new Set<string>();
  for (const e of t.entries) words.add(e.path[0]);
  for (const a of t.appWords) words.add(a.word);
  return [...words].sort();
}

function groups(t: CompletionTable): Map<string, string[]> {
  const g = new Map<string, string[]>();
  for (const e of t.entries) if (e.path.length > 1) g.set(e.path[0], [...(g.get(e.path[0]) ?? []), e.path[1]]);
  for (const a of t.appWords) if (a.second) g.set(a.word, [...(g.get(a.word) ?? []), a.second]);
  return g;
}

/** A bash `case` label that matches exactly this text. */
const label = (s: string) => `"${s.replace(/(["\\$`])/g, '\\$1')}"`;

export function bashFunction(t: CompletionTable): string {
  const g = groups(t);
  const lines: string[] = [];
  lines.push('_telenow_opts() {');
  lines.push('  case "$1" in');
  for (const e of t.entries) lines.push(`    ${label(e.path.join(' '))}) echo ${label(e.options.join(' '))} ;;`);
  lines.push('  esac');
  lines.push('}');
  lines.push('_telenow() {');
  lines.push('  local cur="${COMP_WORDS[COMP_CWORD]}" w1="${COMP_WORDS[1]}" w2="${COMP_WORDS[2]}" opts');
  lines.push('  COMPREPLY=()');
  lines.push('  if [ "$COMP_CWORD" -eq 1 ]; then');
  lines.push(`    COMPREPLY=( $(compgen -W ${label([...firstWords(t), '--help', '--version'].join(' '))} -- "$cur") ); return 0`);
  lines.push('  fi');
  lines.push('  if [ "$COMP_CWORD" -eq 2 ] && [[ "$cur" != -* ]]; then');
  lines.push('    case "$w1" in');
  for (const [word, subs] of g) lines.push(`      ${label(word)}) COMPREPLY=( $(compgen -W ${label(subs.join(' '))} -- "$cur") ); return 0 ;;`);
  lines.push('    esac');
  lines.push('  fi');
  lines.push('  opts="$(_telenow_opts "$w1 $w2")"');
  lines.push('  [ -z "$opts" ] && opts="$(_telenow_opts "$w1")"');
  lines.push('  if [[ "$cur" == -* ]]; then');
  lines.push(`    COMPREPLY=( $(compgen -W "$opts ${t.globals.join(' ')}" -- "$cur") )`);
  lines.push('  else');
  lines.push('    COMPREPLY=( $(compgen -f -- "$cur") )');
  lines.push('  fi');
  lines.push('}');
  lines.push('complete -o filenames -F _telenow telenow');
  return lines.join('\n') + '\n';
}

export function bashScript(t: CompletionTable, version: string): string {
  return [
    `# telenow ${version} — bash completion. Generated by \`telenow completion bash\`; regenerate after an upgrade.`,
    '# Load it now:     source <(telenow completion bash)',
    '# Load it always:  telenow completion bash >> ~/.bashrc',
    bashFunction(t),
  ].join('\n');
}

export function zshScript(t: CompletionTable, version: string): string {
  return [
    `# telenow ${version} — zsh completion. Generated by \`telenow completion zsh\`; regenerate after an upgrade.`,
    '# Load it always:  echo \'source <(telenow completion zsh)\' >> ~/.zshrc',
    '# It runs the bash completion through zsh\'s own bashcompinit.',
    // -i: skip insecure completion folders without stopping to ask (it would hang a script).
    'autoload -U +X compinit && { (( ${+functions[compdef]} )) || compinit -i; }',
    'autoload -U +X bashcompinit && bashcompinit',
    bashFunction(t),
  ].join('\n');
}

const fishQuote = (s: string) => `'${s.replace(/(['\\])/g, '\\$1')}'`;

export function fishScript(t: CompletionTable, version: string): string {
  const g = groups(t);
  const lines = [
    `# telenow ${version} — fish completion. Generated by \`telenow completion fish\`; regenerate after an upgrade.`,
    '# Install:  telenow completion fish > ~/.config/fish/completions/telenow.fish',
    'complete -c telenow -f',
  ];
  const summaries = new Map<string, string>();
  for (const e of t.entries) if (e.path.length === 1) summaries.set(e.path[0], e.summary);
  for (const a of t.appWords) if (!a.second) summaries.set(a.word, a.summary);
  for (const w of firstWords(t)) {
    const d = summaries.get(w) ?? (g.has(w) ? `${w} commands` : '');
    lines.push(`complete -c telenow -n '__fish_use_subcommand' -a ${fishQuote(w)} -d ${fishQuote(d)}`);
  }
  for (const [word, subs] of g) {
    const notYet = `__fish_seen_subcommand_from ${word}; and not __fish_seen_subcommand_from ${[...new Set(subs)].join(' ')}`;
    for (const s of new Set(subs)) {
      const e = t.entries.find((x) => x.path[0] === word && x.path[1] === s);
      const a = t.appWords.find((x) => x.word === word && x.second === s);
      lines.push(`complete -c telenow -n ${fishQuote(notYet)} -a ${fishQuote(s)} -d ${fishQuote(e?.summary ?? a?.summary ?? '')}`);
    }
  }
  for (const e of t.entries) {
    const cond = e.path.map((w) => `__fish_seen_subcommand_from ${w}`).join('; and ');
    for (const o of e.options) lines.push(`complete -c telenow -n ${fishQuote(cond)} -l ${o.slice(2)} -F`);
  }
  for (const o of t.globals) if (o.startsWith('--')) lines.push(`complete -c telenow -l ${o.slice(2)}`);
  return lines.join('\n') + '\n';
}
